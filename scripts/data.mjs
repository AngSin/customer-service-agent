import { readFile, writeFile } from "node:fs/promises";
import { spawnSync } from "node:child_process";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
import {
  catalogStatements,
  executeBatch,
  installFixtures,
  localReferenceInput,
  provisionNamespace,
  verifyNamespace
} from "../shared/fixtures.ts";

const root = fileURLToPath(new URL("../", import.meta.url));

export function dataCommand(args, environment = process.env) {
  const [command, ...extra] = args;
  const commands = [
    "generate",
    "check",
    "seed",
    "verify",
    "reset",
    "seed-demo"
  ];
  if (!commands.includes(command) || extra.length) {
    throw new Error(
      "Usage: node scripts/data.mjs generate|check|seed|verify|reset|seed-demo (no additional flags)"
    );
  }
  if (
    ["seed", "verify", "reset"].includes(command) &&
    environment.CLOUDFLARE_ENV
  ) {
    throw new Error(
      "Local data commands refuse CLOUDFLARE_ENV. Unset it; demo reset is not supported."
    );
  }
  return command;
}

function sqlLiteral(value) {
  if (value === null) return "NULL";
  if (typeof value === "number") return String(value);
  return `'${value.replaceAll("'", "''")}'`;
}

export async function generatedSeedSql() {
  const statements = await catalogStatements();
  return (
    "-- Generated by npm run fixtures:generate. Install catalog only; never reset sessions.\n" +
    statements
      .map(({ sql, values }) => {
        let index = 0;
        return sql.replaceAll("?", () => sqlLiteral(values[index++])) + ";";
      })
      .join("\n") +
    "\n"
  );
}

async function main() {
  const command = dataCommand(process.argv.slice(2));
  process.chdir(root);
  if (command === "generate" || command === "check") {
    const expected = await generatedSeedSql();
    if (command === "generate")
      await writeFile("fixtures/seed-v2.sql", expected);
    else if ((await readFile("fixtures/seed-v2.sql", "utf8")) !== expected) {
      throw new Error("Fixture SQL is stale; run npm run fixtures:generate");
    }
    console.log(
      `Fixture SQL ${command === "generate" ? "generated" : "verified"}.`
    );
    return;
  }
  if (command === "seed-demo") {
    // Explicit catalog bootstrap only. No namespace, reset, or Workflow execution.
    if (
      (await readFile("fixtures/seed-v2.sql", "utf8")) !==
      (await generatedSeedSql())
    ) {
      throw new Error("Fixture SQL is stale; run npm run fixtures:generate");
    }
    const result = spawnSync(
      process.execPath,
      [
        "node_modules/wrangler/bin/wrangler.js",
        "d1",
        "execute",
        "customer-service-demo",
        "--remote",
        "--env",
        "demo",
        "--config",
        "workers/commerce/wrangler.jsonc",
        "--file",
        "fixtures/seed-v2.sql"
      ],
      { stdio: "inherit" }
    );
    if (result.status !== 0) throw new Error("Demo fixture bootstrap failed");
    return;
  }
  const { getPlatformProxy, unstable_splitSqlQuery } = await import("wrangler");
  // Do not read the Vite redirected deploy config or enable remote bindings.
  const proxy = await getPlatformProxy({
    configPath: resolve("workers/commerce/wrangler.jsonc"),
    environment: "",
    persist: { path: resolve(".wrangler/state/v3") },
    remoteBindings: false,
    envFiles: []
  });
  try {
    const db = proxy.env.DB;
    if (command === "reset") {
      const sql = await readFile("fixtures/reset-local.sql", "utf8");
      await executeBatch(
        db,
        unstable_splitSqlQuery(sql).map((sql) => ({ sql, values: [] }))
      );
      console.log(
        "Local namespaces reset. Catalog and migration history preserved. Run npm run db:seed."
      );
      return;
    }
    if (command === "seed") {
      await installFixtures(db);
      const input = await localReferenceInput();
      const existing = await db
        .prepare("SELECT ns FROM demo_sessions WHERE ns = ?")
        .bind(input.ns)
        .first();
      if (!existing) await provisionNamespace(db, input);
    }
    await verifyNamespace(db, "local_reference");
    console.log(
      "Local reference verified: 6 customers, 12 orders, 3 tickets; isolated EUR fixtures and refund history are coherent."
    );
  } finally {
    await proxy.dispose();
  }
}

if (
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  main().catch((error) => {
    console.error(error.message);
    process.exitCode = 1;
  });
}
